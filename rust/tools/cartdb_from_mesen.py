"""Builds `crates/zax-nes/data/cartdb.csv` from Mesen's game database (`MesenNesDB.txt`).

Mesen's database is GPL-3, like Zaxnes; it is itself generated from NewRisingSun's NES 2.0 header
database, BootGod's NesCartDB and Nestopia UE's database (its own header says so). The output
keeps the fields the loader uses, one cartridge per line, sorted by CRC so the lookup can bisect:

    crc,system,mapper,submapper,prg_kib,chr_kib,chr_ram_kib,work_ram_kib,save_ram_kib,battery,mirroring,chip

Run:  python tools/cartdb_from_mesen.py <path to MesenNesDB.txt>
"""

import os
import sys

KEPT_SYSTEMS = {"NesNtsc", "NesPal", "Famicom", "Dendy", "Playchoice", "VsSystem"}


def main() -> None:
    source = sys.argv[1]
    here = os.path.dirname(os.path.abspath(__file__))
    out = os.path.join(here, "..", "crates", "zax-nes", "data", "cartdb.csv")
    rows = {}
    with open(source, encoding="utf-8") as lines:
        for line in lines:
            line = line.rstrip("\n")
            if not line or line.startswith("#"):
                continue
            f = line.split(",")
            if len(f) < 16 or f[1] not in KEPT_SYSTEMS or not f[5].isdigit():
                continue
            crc = f[0].upper()
            submapper = f[15] if f[15].isdigit() else ""
            row = [crc, f[1], f[5], submapper, f[6], f[7], f[8], f[9], f[10], f[11], f[12], f[4]]
            # One line per CRC: the first wins, as in Mesen's own loader.
            rows.setdefault(crc, row)
    os.makedirs(os.path.dirname(out), exist_ok=True)
    with open(out, "w", encoding="utf-8", newline="\n") as file:
        file.write("# Generated by tools/cartdb_from_mesen.py from Mesen's MesenNesDB.txt (GPL-3).\n")
        file.write("# crc,system,mapper,submapper,prg_kib,chr_kib,chr_ram_kib,work_ram_kib,"
                   "save_ram_kib,battery,mirroring,chip\n")
        for crc in sorted(rows):
            file.write(",".join(rows[crc]) + "\n")
    print(f"{len(rows)} cartridges -> {os.path.normpath(out)}")


if __name__ == "__main__":
    main()
