"""Builds a cartridge database in the format of `crates/zax-nes/data/cartdb.csv` straight from
NewRisingSun's NES 2.0 header database (`nes20db.xml`), the main source of Mesen's database.

The key is the CRC-32 of the PRG-ROM followed by the CHR-ROM, the `data_crc` the loader computes;
it is combined from the two CRCs the database gives, as the database's own `rom` CRC also covers
a misc ROM. The database knows neither the chip revision nor the Famicom / NES distinction (Mesen
takes them from NesCartDB): the `chip` column stays empty and a Japanese NTSC cartridge is
`NesNtsc`. Consoles other than the NES, the Famicom, the Dendy, the VS. System and the
PlayChoice-10 (the famiclone types) are left out, as in `cartdb_from_mesen.py`.

Run:  python tools/cartdb_from_nes20db.py <path to nes20db.xml> [--out <csv>]
"""

import argparse
import os
import xml.etree.ElementTree as ElementTree

# console type 0 (NES/Famicom/Dendy) by region, then type 1 and 2.
SYSTEMS = {(0, 0): "NesNtsc", (0, 1): "NesPal", (0, 2): "NesNtsc", (0, 3): "Dendy"}
MIRRORING = {"H": "h", "V": "v", "4": "4", "1": "1"}


def gf2_times(matrix: list[int], vector: int) -> int:
    total = 0
    row = 0
    while vector:
        if vector & 1:
            total ^= matrix[row]
        vector >>= 1
        row += 1
    return total


def gf2_square(matrix: list[int]) -> list[int]:
    return [gf2_times(matrix, matrix[n]) for n in range(32)]


def crc32_combine(crc1: int, crc2: int, len2: int) -> int:
    """The CRC-32 of A followed by B, from CRC(A), CRC(B) and len(B) (zlib's crc32_combine)."""
    if len2 == 0:
        return crc1
    odd = [0xEDB88320] + [1 << n for n in range(31)]
    even = gf2_square(odd)
    odd = gf2_square(even)
    while True:
        even = gf2_square(odd)
        if len2 & 1:
            crc1 = gf2_times(even, crc1)
        len2 >>= 1
        if not len2:
            break
        odd = gf2_square(even)
        if len2 & 1:
            crc1 = gf2_times(odd, crc1)
        len2 >>= 1
        if not len2:
            break
    return crc1 ^ crc2


def size_kib(game: ElementTree.Element, tag: str) -> int:
    node = game.find(tag)
    return int(node.get("size", "0")) // 1024 if node is not None else 0


def save_size(game: ElementTree.Element) -> str:
    """The battery-backed PRG RAM in KiB, or in bytes behind a `b` for a small serial EEPROM, as
    Mesen writes it."""
    node = game.find("prgnvram")
    size = int(node.get("size", "0")) if node is not None else 0
    return "b%d" % size if size % 1024 else str(size // 1024)


def main() -> None:
    here = os.path.dirname(os.path.abspath(__file__))
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("source")
    parser.add_argument(
        "--out", default=os.path.join(here, "..", "crates", "zax-nes", "data", "cartdb.csv")
    )
    args = parser.parse_args()

    root = ElementTree.parse(args.source).getroot()
    rows = {}
    for game in root.iter("game"):
        console = game.find("console")
        kind = int(console.get("type", "0"))
        region = int(console.get("region", "0"))
        system = {1: "VsSystem", 2: "Playchoice"}.get(kind) or SYSTEMS.get((kind, region))
        if system is None:
            continue
        prg = game.find("prgrom")
        chr_rom = game.find("chrrom")
        crc = int(prg.get("crc32"), 16)
        if chr_rom is not None:
            crc = crc32_combine(crc, int(chr_rom.get("crc32"), 16), int(chr_rom.get("size")))
        pcb = game.find("pcb")
        row = [
            "%08X" % crc,
            system,
            pcb.get("mapper", "0"),
            pcb.get("submapper", "0"),
            str(size_kib(game, "prgrom")),
            str(size_kib(game, "chrrom")),
            str(size_kib(game, "chrram")),
            str(size_kib(game, "prgram")),
            save_size(game),
            pcb.get("battery", "0"),
            MIRRORING.get(pcb.get("mirroring", ""), ""),
            "",
        ]
        rows.setdefault(row[0], row)

    os.makedirs(os.path.dirname(os.path.abspath(args.out)), exist_ok=True)
    with open(args.out, "w", encoding="utf-8", newline="\n") as file:
        file.write("# Generated by tools/cartdb_from_nes20db.py from NewRisingSun's nes20db.xml (%s).\n"
                   % root.get("date", "undated"))
        file.write("# crc,system,mapper,submapper,prg_kib,chr_kib,chr_ram_kib,work_ram_kib,"
                   "save_ram_kib,battery,mirroring,chip\n")
        for crc in sorted(rows):
            file.write(",".join(rows[crc]) + "\n")
    print(f"{len(rows)} cartridges -> {os.path.normpath(args.out)}")


if __name__ == "__main__":
    main()
