"""Lists the files of the slang shader pack Zaxnes carries (feature `shaders`).

The pack is a part of libretro/slang-shaders: the presets of `crates/zax-app/shaders/pack-roots.txt`
(a file, or a folder for every preset under it) and everything they need, read from the presets
(`shaderN`, the textures, `#reference`) and the shaders (`#include`). The list goes into
`crates/zax-app/shaders/pack-files.txt`, which the build of zax-app zips into the executable from
the same copy of slang-shaders (`ZAXNES_SLANG_SHADERS`, else `../../slang-shaders` beside the
repository).

    python tools/shader_pack.py G:/3DSen/slang-shaders
"""

import os
import re
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
SHADERS = os.path.join(HERE, "..", "crates", "zax-app", "shaders")


def main():
    root = os.path.abspath(sys.argv[1])
    roots = []
    excluded = []
    for line in open(os.path.join(SHADERS, "pack-roots.txt"), encoding="utf-8"):
        line = line.strip()
        if line.startswith("!"):
            excluded.append(line[1:].strip())
        elif line and not line.startswith("#"):
            roots.append(line)

    def is_excluded(name):
        return any(name == prefix or name.startswith(prefix.rstrip("/") + "/") for prefix in excluded)

    files = set()
    missing = set()

    def rel(path):
        return os.path.relpath(path, root).replace("\\", "/")

    def add_slang(path, seen):
        path = os.path.normpath(path)
        if path in seen:
            return
        seen.add(path)
        if not os.path.isfile(path):
            missing.add(rel(path))
            return
        files.add(rel(path))
        for line in open(path, encoding="utf-8", errors="replace"):
            match = re.match(r'\s*#include\s+["<]([^">]+)[">]', line)
            if match:
                add_slang(os.path.join(os.path.dirname(path), match.group(1)), seen)

    def add_preset(path, seen):
        path = os.path.normpath(path)
        if path in seen:
            return
        seen.add(path)
        if not os.path.isfile(path):
            missing.add(rel(path))
            return
        files.add(rel(path))
        base = os.path.dirname(path)
        values = {}
        for line in open(path, encoding="utf-8", errors="replace"):
            text = line.strip()
            match = re.match(r'#reference\s+"([^"]+)"', text)
            if match:
                add_preset(os.path.join(base, match.group(1)), seen)
                continue
            if text.startswith("#") or "=" not in text:
                continue
            key, value = text.split("=", 1)
            values[key.strip()] = value.strip().strip('"')
        for key, value in values.items():
            if re.fullmatch(r"shader\d+", key):
                add_slang(os.path.join(base, value), seen)
        for name in values.get("textures", "").split(";"):
            name = name.strip()
            if name and name in values:
                texture = os.path.normpath(os.path.join(base, values[name]))
                if os.path.isfile(texture):
                    files.add(rel(texture))
                else:
                    missing.add(rel(texture))

    seen = set()
    for entry in roots:
        path = os.path.join(root, entry)
        if os.path.isdir(path):
            for folder, _, names in os.walk(path):
                for name in sorted(names):
                    preset = os.path.join(folder, name)
                    if name.endswith(".slangp") and not is_excluded(rel(preset)):
                        add_preset(preset, seen)
        elif entry.endswith(".slangp"):
            add_preset(path, seen)
        else:
            # A plain file (a licence, a read-me) goes in as it is.
            if os.path.isfile(path):
                files.add(rel(path))
            else:
                missing.add(entry)

    kept_out = sorted(name for name in files if is_excluded(name))
    for name in kept_out:
        print("excluded but needed by a preset of the pack:", name)
    files = set(name for name in files if not is_excluded(name))

    commit = subprocess.run(
        ["git", "-C", root, "rev-parse", "HEAD"], capture_output=True, text=True
    ).stdout.strip()
    with open(os.path.join(SHADERS, "pack-files.txt"), "w", encoding="utf-8", newline="\n") as out:
        out.write("# Generated by tools/shader_pack.py from libretro/slang-shaders %s\n" % commit)
        for name in sorted(files):
            out.write(name + "\n")
    size = sum(os.path.getsize(os.path.join(root, name)) for name in files)
    print("%d files, %d KiB, commit %s" % (len(files), size // 1024, commit))
    for name in sorted(missing):
        print("missing (the preset refers to it, the collection lacks it):", name)


if __name__ == "__main__":
    main()
