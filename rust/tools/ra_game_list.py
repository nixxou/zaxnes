"""Builds `crates/zax-app/data/ra_games.csv`: the NES and Famicom Disk System games RetroAchievements
has achievements for, with every ROM hash it accepts for each.

The catalogue reads it to show a game as supporting achievements before the real check (rcheevos
asks the server when the game starts); a ROM whose hash is not listed is shown as not supported
until that check says otherwise. The hashes are RetroAchievements' own: MD5 of the ROM without its
16-byte header (iNES or fwNES), equal to the catalogue's `data_md5` on a clean ROM.

One line per hash, sorted by hash so the lookup can bisect:

    md5,game_id,console,achievements,points,title

It needs a RetroAchievements Web API key (retroachievements.org > Settings > Keys). The key is read
from the `RA_API_KEY` variable or from the file given with `--key-file`; it is never written
anywhere. Run it again at each release to refresh the list.

Run:  python tools/ra_game_list.py [--key-file <file>] [--out <csv>]
"""

import argparse
import csv
import io
import json
import os
import sys
import time
import urllib.error
import urllib.parse
import urllib.request

API = "https://retroachievements.org/API/"
# The console names as RetroAchievements gives them; the ids are asked, not assumed.
CONSOLES = {"NES/Famicom": "nes", "Famicom Disk System": "fds"}
USER_AGENT = "Zaxnes-ra-game-list/1"


def call(endpoint: str, key: str, **params: object) -> object:
    """One Web API call, retried a few times when the server is busy."""
    query = urllib.parse.urlencode({"y": key, **params})
    request = urllib.request.Request(API + endpoint + "?" + query, headers={"User-Agent": USER_AGENT})
    for attempt in range(4):
        try:
            with urllib.request.urlopen(request, timeout=60) as response:
                return json.load(response)
        except urllib.error.HTTPError as error:
            if error.code in (401, 403):
                sys.exit("RetroAchievements refused the API key (HTTP %d)." % error.code)
            if error.code != 429 and error.code < 500 or attempt == 3:
                raise
        except urllib.error.URLError:
            if attempt == 3:
                raise
        time.sleep(5 * (attempt + 1))
    raise RuntimeError("unreachable")


def read_key(key_file: str | None) -> str:
    if key_file:
        with open(key_file, encoding="utf-8") as file:
            key = file.read().strip()
    else:
        key = os.environ.get("RA_API_KEY", "").strip()
    if not key:
        sys.exit("No API key: set RA_API_KEY or give --key-file.")
    return key


def main() -> None:
    here = os.path.dirname(os.path.abspath(__file__))
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--key-file", help="file holding the Web API key")
    parser.add_argument(
        "--out", default=os.path.join(here, "..", "crates", "zax-app", "data", "ra_games.csv")
    )
    args = parser.parse_args()
    key = read_key(args.key_file)

    consoles = {
        entry["Name"]: int(entry["ID"])
        for entry in call("API_GetConsoleIDs.php", key)
        if entry.get("Name") in CONSOLES
    }
    missing = set(CONSOLES) - set(consoles)
    if missing:
        sys.exit("RetroAchievements no longer lists: %s" % ", ".join(sorted(missing)))

    rows = {}
    games = 0
    for name, console_id in sorted(consoles.items()):
        # f=1: only games with published achievements; h=1: with their hashes.
        listed = call("API_GetGameList.php", key, i=console_id, f=1, h=1)
        for game in listed:
            if int(game.get("NumAchievements") or 0) == 0:
                continue
            games += 1
            for md5 in game.get("Hashes") or []:
                md5 = md5.strip().lower()
                if len(md5) != 32:
                    continue
                row = [
                    md5,
                    str(game["ID"]),
                    CONSOLES[name],
                    str(game.get("NumAchievements") or 0),
                    str(game.get("Points") or 0),
                    game.get("Title", "").strip(),
                ]
                # A hash in two games should not happen; the lowest game id wins, so a run is
                # reproducible.
                if md5 not in rows or int(row[1]) < int(rows[md5][1]):
                    rows[md5] = row
        print("%s (console %d): %d games so far" % (name, console_id, games))

    buffer = io.StringIO()
    buffer.write("# Generated by tools/ra_game_list.py from the RetroAchievements Web API.\n")
    buffer.write("# md5,game_id,console,achievements,points,title\n")
    writer = csv.writer(buffer, lineterminator="\n")
    for md5 in sorted(rows):
        writer.writerow(rows[md5])
    os.makedirs(os.path.dirname(os.path.abspath(args.out)), exist_ok=True)
    with open(args.out, "w", encoding="utf-8", newline="\n") as file:
        file.write(buffer.getvalue())
    print("%d games, %d hashes -> %s" % (games, len(rows), os.path.normpath(args.out)))


if __name__ == "__main__":
    main()
