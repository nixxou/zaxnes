WIDTH, HEIGHT = 128, 24
BASE = 256 + 0xD0
COLOUR = {0: 0, 1: 3, 2: 1}  # outline in city blue (3), fill white (1)


def main():
    canvas = [[0] * WIDTH for _ in range(HEIGHT)]
    for y, row in enumerate(FLAPPY.strip('\n').split('\n')):
        for x, c in enumerate(row):
            canvas[y][x] = '.12'.index(c)
    fill = set()
    x0 = 56
    for top, mask in LETTERS:
        rows = mask.strip('\n').split('\n')
        for y, row in enumerate(rows):
            for x, c in enumerate(row):
                if c == '1':
                    fill.add((x0 + x, top + y))
        x0 += len(rows[0]) + 1
    assert x0 <= WIDTH, x0
    for y in range(HEIGHT):
        for x in range(55, WIDTH):
            if (x, y) in fill:
                canvas[y][x] = 2
            elif any((x + dx, y + dy) in fill for dx in (-1, 0, 1) for dy in (-1, 0, 1)) \
                    or (x, y - 2) in fill or (x - 1, y - 2) in fill:
                canvas[y][x] = 1
            elif x > 55:
                canvas[y][x] = 0
    data = bytearray(open('char.chr', 'rb').read())
    for y in range(HEIGHT):
        for x in range(WIDTH):
            o = (BASE + (y // 8) * 16 + x // 8) * 16
            bit = 0x80 >> (x % 8)
            v = COLOUR[canvas[y][x]]
            data[o + y % 8] = (data[o + y % 8] & ~bit) | (bit if v & 1 else 0)
            data[o + 8 + y % 8] = (data[o + 8 + y % 8] & ~bit) | (bit if v & 2 else 0)
    open('char.chr', 'wb').write(data)


main()
