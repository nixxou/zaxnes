# The wing (w white, k outline), three positions, laid over the body at the given offset.
WINGS = [
    """
.kkkk.
kwwwwk
kwwwwwk
.kkkkk.
""",
    """
.......
kkkkkk.
kwwwwwk
.kkkkk.
""",
    """
.......
.......
kkkkkk.
kwwwwwk
kwwwwk.
.kkkk..
""",
]
WING_AT = {'level': (1, 6), 'up': (2, 8), 'down': (1, 5)}

COLOURS = {'k': (20, 20, 20), 'y': (250, 210, 40), 'l': (255, 240, 150), 'w': (255, 255, 255),
           'r': (220, 50, 30)}


def grid(text):
    rows = text.strip('\n').split('\n')
    width = max(len(r) for r in rows)
    return [list(r.ljust(width, '.')) for r in rows]


def pose(name, wing):
    body = grid({'level': LEVEL, 'up': UP, 'down': DOWN}[name])
    ox, oy = WING_AT[name]
    for y, row in enumerate(grid(WINGS[wing])):
        for x, c in enumerate(row):
            if c != '.' and 0 <= oy + y < len(body) and 0 <= ox + x < len(body[0]):
                body[oy + y][ox + x] = c
    return body


def main():
    from PIL import Image
    cell = 26
    image = Image.new('RGB', (cell * 9, 18), (110, 190, 240))
    for i, name in enumerate(('level', 'up', 'down')):
        for wing in range(3):
            for y, row in enumerate(pose(name, wing)):
                for x, c in enumerate(row):
                    if c != '.':
                        image.putpixel(((i * 3 + wing) * cell + 1 + x, 1 + y), COLOURS[c])
    image.resize((image.width * 5, image.height * 5), Image.NEAREST).save(sys.argv[1])


if __name__ == '__main__':
    main()
