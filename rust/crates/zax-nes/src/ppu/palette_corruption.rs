//! Palette RAM corruption when rendering stops, or `v` leaves palette RAM, on a visible dot
//! (lot FIDELITY step 32, `docs/review/FIDELITY-LEADS.md` D5).
//!
//! nesdev, "PPU registers" (PPUMASK): "Turning rendering off mid-screen can corrupt palette
//! RAM." The rules and the table are `TriCNES`'s (MIT, (c) 2025 Chris Siebert,
//! <https://github.com/100thCoin/TriCNES>, `CorruptPalettes`), found by its author with a test
//! cart on his console, which he calls "good enough" and in part not understood; he applies them
//! in alignment 2 only ("consistent on alignment 2, and very hit or miss on other alignments"),
//! and so does this core. The table below is generated from his source (`conv_palette.py` of the
//! study), not retyped. Sprite palettes and the single discoloured pixel he mentions are not
//! modelled, by him or here.

use super::Ppu2C02;

impl Ppu2C02 {
    /// Corrupts the background palettes as `TriCNES` does, `color` (0 to 3) being the colour
    /// index of the pixel drawn at that moment and `v` the address register then.
    pub(super) fn corrupt_palettes(&mut self, color: u8) {
        let mut p = [0u8; 16];
        p.copy_from_slice(&self.palette_raw[..16]);
        let mut c = p;
        if color == 0 {
            // "simply take the low nybble from the V register. that's the color to corrupt."
            let low = usize::from(self.v & 0x0F);
            let row = usize::from(self.v & 0x0C);
            c[low] = (p[0] & p[row]) | (p[0] & p[low]) | (p[row] & p[low]);
        } else {
            corrupt_by_table(color, self.v & 0x0F, &p, &mut c);
        }
        for (entry, value) in self.palette_raw.iter_mut().zip(c) {
            *entry = value & 0x3F;
        }
        self.refresh_palette_views();
    }
}

// Generated by conv_palette.py from TriCNES (MIT, (c) 2025 Chris Siebert), `CorruptPalettes`,
// colour indices 1 to 3; see `corrupt_palettes` for colour 0. Do not edit by hand.
#[allow(clippy::too_many_lines, clippy::match_same_arms)]
pub(super) fn corrupt_by_table(color: u8, nybble: u16, p: &[u8; 16], c: &mut [u8; 16]) {
    match (color, nybble) {
        (1, 0x0) => {
            c[0x0] = (p[0x1] & p[0xD]) | p[0x0];
            c[0x4] = p[0x5];
            c[0x8] = p[0x9];
            c[0xC] = p[0xD];
        }
        (1, 0x2) => {
            c[0x2] = (p[0x2] | p[0xD]) & p[0x3];
            c[0x3] = (p[0x1] | p[0x2]) & p[0x3];
            c[0x6] = (p[0x6] | p[0x5]) & p[0x7];
            c[0xA] = (p[0xA] | p[0x9]) & p[0xB];
            c[0xE] = p[0xD];
            c[0xF] = p[0xD];
        }
        (1, 0x3) => {
            c[0x3] &= p[0x1] | p[0xD];
            c[0xF] = p[0xD];
        }
        (1, 0x4) => {
            c[0x0] = p[0x1];
            c[0x4] = (p[0x5] & p[0xD]) | p[0x4];
            c[0x8] = p[0x9];
            c[0xC] = p[0xD];
        }
        (1, 0x6) => {
            c[0x2] = (p[0x2] | p[0x1]) & p[0x3];
            c[0x6] = (p[0x6] | p[0x7]) & p[0xD];
            c[0x7] = (p[0x7] | p[0x6]) & p[0x5];
            c[0xA] = (p[0xA] | p[0x9]) & p[0xB];
            c[0xE] = p[0xD];
            c[0xF] = p[0xD];
        }
        (1, 0x7) => {
            c[0x7] &= p[0x5] | p[0xD];
            c[0xF] = p[0xD];
        }
        (1, 0x8) => {
            c[0x0] = p[0x1];
            c[0x4] = p[0x5];
            c[0x8] = (p[0x9] & p[0xD]) | p[0x8];
            c[0xC] = p[0xD];
        }
        (1, 0xA) => {
            c[0x2] = (p[0x2] | p[0x1]) & p[0x3];
            c[0x6] = (p[0x6] | p[0xD]) & p[0x7];
            c[0xA] = (p[0xB] | p[0xD]) & p[0xA];
            c[0xB] = (p[0x9] | p[0xA]) & p[0xB];
            c[0xE] = p[0xD];
            c[0xF] = p[0xD];
        }
        (1, 0xB) => {
            c[0xB] &= p[0x9] | p[0xD];
            c[0xF] = p[0xD];
        }
        (1, 0xC) => {
            c[0x0] = p[0x1];
            c[0x4] = p[0x5];
            c[0x8] = p[0x9];
            c[0xC] = p[0xD];
        }
        (1, 0xE) => {
            c[0x2] = (p[0x2] | p[0x1]) & p[0x3];
            c[0x6] = (p[0x6] | p[0xD]) & p[0x7];
            c[0xA] = (p[0xA] | p[0x9]) & p[0xB];
            c[0xE] = p[0xD];
            c[0xF] = p[0xD];
        }
        (1, 0xF) => {
            c[0xF] = p[0xD];
        }
        (2, 0x0) => {
            c[0x0] = p[0x0] | (p[0x2] & p[0xE]);
            c[0x4] = p[0x6];
            c[0x8] = p[0xA];
            c[0xC] = p[0xE];
        }
        (2, 0x1) => {
            c[0x1] = (p[0x2] | p[0x1] | p[0xE]) & (p[0x3] | p[0xE]);
            c[0x3] = (p[0x2] | p[0xE] | 0x3C) & p[0x3];
            c[0x5] = (p[0x6] | p[0x7]) & p[0x5];
            c[0x9] = (p[0xA] | p[0xB]) & p[0x9];
            c[0xD] = p[0xE];
            c[0xF] = p[0xE];
        }
        (2, 0x3) => {
            c[0x3] &= p[0x2] | p[0xE];
            c[0xF] = p[0xE];
        }
        (2, 0x4) => {
            c[0x0] = p[0x2];
            c[0x4] = p[0x4] | (p[0x6] & p[0xE]);
            c[0x8] = p[0xA];
            c[0xC] = p[0xE];
        }
        (2, 0x5) => {
            c[0x1] = (p[0x2] | p[0x1]) & p[0x3];
            c[0x5] = (p[0xE] | p[0x6]) & p[0x5];
            c[0x7] = (p[0xE] | p[0x6]) & p[0x7];
            c[0xD] = p[0xE];
            c[0xF] = p[0xE];
        }
        (2, 0x7) => {
            c[0x7] &= p[0x6] | p[0xE];
        }
        (2, 0x8) => {
            c[0x0] = p[0x2];
            c[0x4] = p[0x6];
            c[0x8] = p[0x8] | (p[0xA] & p[0xE]);
            c[0xC] = p[0xE];
        }
        (2, 0x9) => {
            c[0x1] = (p[0x2] | p[0x1]) & p[0x3];
            c[0x5] = (p[0x6] | p[0x5]) & p[0x7];
            c[0x9] = (p[0xE] | p[0xA] | 0x01) & p[0x9];
            c[0xB] = (p[0xE] | p[0xA] | 0x31) & p[0xB];
            c[0xD] = p[0xE];
            c[0xF] = p[0xE];
        }
        (2, 0xB) => {
            c[0xB] &= p[0xA] | p[0xE];
            c[0xF] = p[0xE];
        }
        (2, 0xC) => {
            c[0x0] = p[0x2];
            c[0x4] = p[0x6];
            c[0x8] = p[0xA];
            c[0xC] = p[0xE];
        }
        (2, 0xD) => {
            c[0x1] = (p[0x2] | p[0x1]) & p[0x3];
            c[0x5] = (p[0x6] | p[0x5]) & p[0x7];
            c[0x9] = (p[0xA] | p[0x9]) & p[0xB];
            c[0xD] = p[0xE];
            c[0xF] = p[0xE];
        }
        (2, 0xF) => {
            c[0xF] = p[0xE];
        }
        (3, 0x0) => {
            c[0x0] = p[0x3] | (p[0xF] & p[0x0]);
            c[0x4] &= p[0x7];
            c[0x8] &= p[0x9] | p[0xA] | p[0xB] | p[0xF] | 0x22;
            c[0xC] = p[0xF];
        }
        (3, 0x1) => {
            c[0x1] = (p[0x1] | p[0xF]) & p[0x3];
            c[0x5] = p[0x7];
            c[0x9] = p[0xB];
            c[0xD] = p[0xF];
        }
        (3, 0x2) => {
            c[0x2] = (p[0x3] | p[0xF]) & p[0x3];
            c[0x6] = p[0x7];
            c[0xA] = p[0xB];
            c[0xE] = p[0xF];
        }
        (3, 0x4) => {
            c[0x0] &= (p[0xF] ^ 0xFF) | p[0x1] | p[0x2] | p[0x3] | 0x7;
            c[0x4] &= p[0x7] | p[0xF];
            c[0x8] &= p[0xB] | p[0xF] | (p[0xC] ^ 0xFF);
            c[0xC] = (p[0x7] & p[0xF]) | p[0xC];
        }
        (3, 0x5) => {
            c[0x1] = p[0x3];
            c[0x5] = (p[0x5] | p[0xF]) & p[0x7];
            c[0x9] = p[0xB];
            c[0xD] = p[0xF];
        }
        (3, 0x6) => {
            c[0x2] = p[0x3];
            c[0x6] = (p[0x6] | p[0xF]) & p[0x7];
            c[0xA] = p[0xB];
            c[0xE] = p[0xF];
        }
        (3, 0x8) => {
            c[0x0] &= (p[0xF] ^ 0xFF) | p[0x1] | p[0x2] | p[0x3] | 0x23;
            c[0x4] = p[0x7];
            c[0x8] &= p[0xB] | p[0xF] | (p[0xC] ^ 0xFF);
            c[0xC] = (p[0xB] & p[0xF]) | p[0xC];
        }
        (3, 0x9) => {
            c[0x1] = p[0x3];
            c[0x5] = p[0x7];
            c[0x9] = (p[0x9] | p[0xF]) & p[0xB];
            c[0xD] = p[0xF];
        }
        (3, 0xA) => {
            c[0x2] = p[0x3];
            c[0x6] = p[0x7];
            c[0xA] = (p[0xA] | p[0xF]) & p[0xB];
            c[0xE] = p[0xF];
        }
        (3, 0xC) => {
            c[0x0] &= (p[0xF] ^ 0xFF) | p[0x1] | p[0x2] | p[0x3] | 0x37;
            c[0x4] = p[0x7];
            c[0x8] &= p[0xB] | 0x2F;
            c[0xC] = p[0xF];
        }
        (3, 0xD) => {
            c[0x1] = p[0x3];
            c[0x5] = p[0x7];
            c[0x9] = p[0xB];
            c[0xD] = p[0xF];
        }
        (3, 0xE) => {
            c[0x2] = p[0x3];
            c[0x6] = p[0x7];
            c[0xA] = p[0xB];
            c[0xE] = p[0xF];
        }
        _ => {}
    }
}
