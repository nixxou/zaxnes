//! The 6502 microcode table and its micro-operation alphabet.
//!
//! Ported from BizHawk 2.11.1 `src/BizHawk.Emulation.Cores/CPUs/MOS 6502X/Execute.cs`
//! (the `Uop` enum, the `Microcode` table and the `VOP_*` constants). MIT; see
//! `LICENSE-BizHawk`.
//!
//! Two properties of this file are load-bearing and must not be "tidied":
//!
//! 1. **The variant order is the C# order.** `MOS6502X.AtStart` and
//!    `MOS6502X.AtInstructionStart` both test `Microcode[opcode][mi] >= Uop.End`, which is an
//!    ordering comparison on the enum's own discriminants. In the C# `End` is followed by
//!    `End_ISpecial`, `End_SuppressInterrupt`, `Jam` and then the seven micro-ops under the
//!    comment "More unofficial micro-ops" — so those seven also answer "at an instruction
//!    start", which is a quirk of where they were appended rather than a decision. Reordering
//!    the variants, or sorting them, would silently change that predicate.
//! 2. **Twenty variants are never named by any row** of the table: `Unsupported`, `DecS`,
//!    `NZ_X`, `NZ_Y`, `NZ_A`, `RelBranch_Stage2` and the fourteen `_Alu` sub-ops. They are
//!    vestigial in the C# too. They are kept because of point 1.
//!
//! The table was transliterated mechanically from the C# and has 264 rows: 256 real opcodes
//! followed by the eight `VOP_*` pseudo-opcodes, in that order, so that `MICROCODE[opcode]`
//! indexes with the opcode byte exactly as the C# does.

// The C# names, kept deliberately: this file is meant to be read beside `Execute.cs`, and a
// Rust-cased `abs_idx_rmw_stage6_slo` would make that comparison harder, not easier.
#![allow(non_camel_case_types)]
// `NOP` and `JSR` are the C#'s micro-operation names, not acronyms this port chose to shout.
#![allow(clippy::upper_case_acronyms)]

