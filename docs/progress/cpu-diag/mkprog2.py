"""Second set of programs for the CPU differential: IRQ, DMC DMA, branches, every legal opcode."""
import sys, os

def image(code, handler=b'\x40'):
    prg = bytearray(0x7FFA)
    code = bytes([0xA2, 0xFF, 0x9A]) + code
    prg[:len(code)] = code
    prg[0x1000:0x1000 + len(handler)] = handler
    return bytes(prg)

out = sys.argv[1]

# IRQ: frame counter in 4-step mode with IRQ (writes $4017=0), CLI, spin; handler reads $4015
# (acknowledges) then RTI.
irq = bytes([
    0xA9, 0x00, 0x8D, 0x17, 0x40,   # $4017 = 0
    0x58,                           # CLI
    0xE8, 0xC8, 0x4C, 0x09, 0x80,   # spin: INX INY JMP spin ($8009)
])
open(os.path.join(out, 'irq.bin'), 'wb').write(image(irq, bytes([0xAD, 0x15, 0x40, 0x40])))

# DMC DMA: a looping sample at $C000 (rate 15, length 1), started, while the CPU runs a mix of
# reads and writes (DMA lands on different cycle kinds).
dmc = bytes([
    0xA9, 0x4F, 0x8D, 0x10, 0x40,   # $4010 = $4F: loop, rate 15
    0xA9, 0x00, 0x8D, 0x12, 0x40,   # $4012 = 0: $C000
    0xA9, 0x00, 0x8D, 0x13, 0x40,   # $4013 = 0: 1 byte
    0xA9, 0x10, 0x8D, 0x15, 0x40,   # $4015 = $10: start
    0xAD, 0x00, 0x02,               # loop ($8017): LDA $0200
    0x8D, 0x01, 0x02,               # STA $0201
    0xEE, 0x02, 0x02,               # INC $0202
    0x48, 0x68,                     # PHA PLA
    0x4C, 0x17, 0x80,               # JMP loop
])
open(os.path.join(out, 'dmc.bin'), 'wb').write(image(dmc))

# Branches: taken, not taken, taken across a page, backwards.
br = bytearray()
br += bytes([0xA9, 0x00])           # LDA #0 (Z set)
br += bytes([0xF0, 0x02, 0xEA, 0xEA])   # BEQ +2 (taken)
br += bytes([0xD0, 0x02])           # BNE (not taken)
br += bytes([0xA2, 0x00])           # LDX #0
pad = 0xF0 - (3 + len(br))          # place a branch so it crosses into $8100
br += bytes([0xEA]) * pad
br += bytes([0xF0, 0x20])           # BEQ +$20 from $80F0+2 -> $8112 (page cross)
br += bytes([0xEA]) * 0x20
br += bytes([0x4C, 0x03, 0x80])     # JMP start
open(os.path.join(out, 'branch.bin'), 'wb').write(image(bytes(br)))

