"""Third set for the CPU differential: the hard cases."""
import sys, os
out = sys.argv[1]

def image(code, handler=b'\x40', extra=None):
    prg = bytearray(0x7FFA)
    code = bytes([0xA2, 0xFF, 0x9A]) + code
    prg[:len(code)] = code
    prg[0x1000:0x1000 + len(handler)] = handler
    for offset, data in (extra or {}).items():
        prg[offset:offset + len(data)] = data
    return bytes(prg)

def save(name, data):
    open(os.path.join(out, name + '.bin'), 'wb').write(data)

DMC_START = bytes([
    0xA9, 0x4F, 0x8D, 0x10, 0x40,   # rate 15, loop
    0xA9, 0x00, 0x8D, 0x12, 0x40, 0xA9, 0x00, 0x8D, 0x13, 0x40,
    0xA9, 0x10, 0x8D, 0x15, 0x40,
])

# DMC fetches colliding with OAM DMAs: OAM DMA every loop while the sample plays.
save('dmcoam', image(DMC_START + bytes([
    0xA9, 0x02, 0x8D, 0x14, 0x40,   # loop ($8017): $4014 = 2
    0xE8, 0xC8,                     # INX INY (shift the phase each loop)
    0x4C, 0x17, 0x80,
])))

# Controller reads while DMC fetches land on them (the double-read of $4016).
save('dmc4016', image(DMC_START + bytes([
    0xA9, 0x01, 0x8D, 0x16, 0x40, 0xA9, 0x00, 0x8D, 0x16, 0x40,   # loop ($8017): strobe
    0xAD, 0x16, 0x40, 0x8D, 0x00, 0x03, 0xAD, 0x16, 0x40, 0x8D, 0x01, 0x03,
    0xAD, 0x16, 0x40, 0x8D, 0x02, 0x03, 0xAD, 0x17, 0x40, 0x8D, 0x03, 0x03, 0xE8,
    0x4C, 0x17, 0x80,
])))

# $2007 reads while DMC fetches land on them.
save('dmc2007', image(DMC_START + bytes([
    0xA9, 0x20, 0x8D, 0x06, 0x20, 0xA9, 0x00, 0x8D, 0x06, 0x20,   # loop: $2006 = $2000
    0xAD, 0x07, 0x20, 0xAD, 0x07, 0x20, 0xAD, 0x07, 0x20, 0xE8,
    0x4C, 0x17, 0x80,
])))

# Stable illegal opcodes, every addressing mode they have.
ill = bytearray([0xA9, 0x05, 0x85, 0x10, 0xA9, 0x03, 0x85, 0x11, 0xA2, 0x01, 0xA0, 0x02])
for op, size in [
    (0xA7, 1), (0xB7, 1), (0xAF, 2), (0xBF, 2), (0xA3, 1), (0xB3, 1),       # LAX
    (0x87, 1), (0x97, 1), (0x8F, 2), (0x83, 1),                             # SAX
    (0xC7, 1), (0xD7, 1), (0xCF, 2), (0xDF, 2), (0xDB, 2), (0xC3, 1), (0xD3, 1),  # DCP
    (0xE7, 1), (0xF7, 1), (0xEF, 2), (0xFF, 2), (0xFB, 2), (0xE3, 1), (0xF3, 1),  # ISC
    (0x07, 1), (0x17, 1), (0x0F, 2), (0x1F, 2), (0x1B, 2), (0x03, 1), (0x13, 1),  # SLO
    (0x27, 1), (0x37, 1), (0x2F, 2), (0x3F, 2), (0x3B, 2), (0x23, 1), (0x33, 1),  # RLA
    (0x47, 1), (0x57, 1), (0x4F, 2), (0x5F, 2), (0x5B, 2), (0x43, 1), (0x53, 1),  # SRE
    (0x67, 1), (0x77, 1), (0x6F, 2), (0x7F, 2), (0x7B, 2), (0x63, 1), (0x73, 1),  # RRA
    (0x0B, 1), (0x2B, 1), (0x4B, 1), (0x6B, 1), (0xCB, 1), (0xEB, 1),       # ANC ALR ARR AXS SBC
    (0x1A, 0), (0x3A, 0), (0x5A, 0), (0x7A, 0), (0xDA, 0), (0xFA, 0),       # NOP implied
    (0x80, 1), (0x04, 1), (0x14, 1), (0x0C, 2), (0x1C, 2), (0x3C, 2),       # NOP read forms
]:
    ill.append(op)
    if size == 1:
        ill.append(0x10)
    elif size == 2:
        ill += bytes([0xF8, 0x02])
ill += bytes([0xA2, 0xFF, 0x9A, 0x4C, 0x03, 0x80])
save('illegal', image(bytes(ill)))

# IRQ and NMI against branches: frame IRQ on, NMI on, a loop of taken branches (the branch
# interrupt-delay quirk), the handlers acknowledge.
save('intbranch', image(bytes([
    0xA9, 0x00, 0x8D, 0x17, 0x40,   # frame IRQ on
    0xA9, 0x80, 0x8D, 0x00, 0x20,   # NMI on
    0x58,                           # CLI
    0xA9, 0x00,                     # LDA #0
    0xF0, 0x00,                     # loop ($800E): BEQ +0 (taken, no page cross)
    0xF0, 0xFC,                     # BEQ loop
]), handler=bytes([0x48, 0xAD, 0x15, 0x40, 0x8D, 0x00, 0x03, 0xAD, 0x02, 0x20, 0x8D, 0x01, 0x03, 0x68, 0x40])))

# $4017 five-step mode, then back to four-step with IRQ, writes on both parities.
save('fc5', image(bytes([
    0xA9, 0x80, 0x8D, 0x17, 0x40,   # 5-step
    0xA2, 0x00, 0xCA, 0xD0, 0xFD,   # wait ~1280 cycles
    0xA9, 0x00, 0x8D, 0x17, 0x40,   # 4-step, IRQ on
    0x58, 0xE8, 0x4C, 0x15, 0x80,   # CLI, spin
]), handler=bytes([0xAD, 0x15, 0x40, 0x8D, 0x00, 0x03, 0x40])))
print('ok')
