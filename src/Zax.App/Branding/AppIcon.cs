using System.Globalization;
using System.Reflection;
using Zax.Platform;
using Zax.Render.Assets;

namespace Zax.App.Branding;

/// <summary>
/// The application icon of lot ICON-1, read from the assembly's own resources.
/// </summary>
/// <remarks>
/// <para>
/// Two icons travel with <c>Zaxnes.exe</c> and they are not the same thing. The Win32 icon
/// resource, which Explorer and the taskbar read, comes from <c>branding/zaxnes.ico</c> through
/// the <c>ApplicationIcon</c> property of the project — the toolchain compiles it in and no code
/// is involved. The <b>window</b> icon is this class: GLFW takes decoded RGBA rather than an
/// <c>.ico</c>, so the PNG sizes of <c>branding/</c> are embedded as resources and decoded here
/// with <see cref="PngImage"/>, the reader SPEC-06 already needs.
/// </para>
/// <para>
/// The icon is cosmetic. A resource that is absent — a build that embedded none, a trimmed
/// assembly — or one that does not decode must never keep the program from starting, so nothing
/// here throws: the sizes that work are returned, the rest are counted, and the caller logs one
/// line and carries on.
/// </para>
/// <para>
/// The assets are the project's own (<c>branding/zaxnes-icon-*.png</c>, made for Zaxnes, GPL-3.0,
/// listed in <c>ASSETS-LICENSES.md</c>), which is the exception REQ-PUB-002 makes for files
/// generated by the project. They are embedded rather than copied, so the published folder gains
/// no file at all.
/// </para>
/// </remarks>
internal static class AppIcon
{
    /// <summary>
    /// Prefix the embedded icon resources share. The suffix is the square size in pixels and
    /// <c>.png</c>; the names are set by <c>LogicalName</c> in <c>Zax.App.csproj</c>.
    /// </summary>
    internal const string ResourcePrefix = "Zax.App.Branding.zaxnes-icon-";

    /// <summary>
    /// The square sizes the executable embeds, smallest first. Lot ICON-1 asks for 16, 32, 48
    /// and 256 at the very least; 24, 64 and 128 are the remaining entries of
    /// <c>branding/zaxnes.ico</c>, so the window manager has the same choice as Explorer.
    /// </summary>
    internal static IReadOnlyList<int> Sizes { get; } = [16, 24, 32, 48, 64, 128, 256];

    private static string ResourceName(int size) =>
        string.Create(CultureInfo.InvariantCulture, $"{ResourcePrefix}{size}.png");

    /// <summary>
    /// The raw bytes of the embedded PNG for <paramref name="size"/>, or <see langword="null"/>
    /// when the assembly does not carry it.
    /// </summary>
    internal static byte[]? ReadResource(int size, Assembly? assembly = null)
    {
        assembly ??= typeof(AppIcon).Assembly;

        try
        {
            using Stream? stream = assembly.GetManifestResourceStream(ResourceName(size));
            if (stream is null)
            {
                return null;
            }

            using MemoryStream copy = new();
            stream.CopyTo(copy);
            return copy.ToArray();
        }
        catch (Exception exception) when (exception is IOException
            or FileLoadException
            or NotSupportedException)
        {
            return null;
        }
    }

    /// <summary>
    /// Decodes the embedded icon, skipping anything that is missing or broken.
    /// </summary>
    /// <param name="problems">
    /// One line per size that could not be used, for the caller's log. Empty when every size
    /// decoded.
    /// </param>
    /// <returns>The sizes that decoded, smallest first; empty when none did.</returns>
    internal static IReadOnlyList<WindowIconImage> Load(out IReadOnlyList<string> problems)
    {
        List<WindowIconImage> images = [];
        List<string> failures = [];

        foreach (int size in Sizes)
        {
            byte[]? bytes = ReadResource(size);
            if (bytes is null)
            {
                failures.Add($"{size} px: the resource is not in the assembly");
                continue;
            }

            if (TryDecode(bytes, size, out WindowIconImage image, out string? reason))
            {
                images.Add(image);
            }
            else
            {
                failures.Add($"{size} px: {reason}");
            }
        }

        problems = failures;
        return images;
    }

    /// <summary>
    /// Decodes one embedded PNG into the RGBA buffer the window-icon call wants, and checks it
    /// really is the square image the resource name claims.
    /// </summary>
    /// <param name="bytes">The PNG file.</param>
    /// <param name="size">The square size the resource name declares; 0 to accept any.</param>
    /// <param name="image">The decoded image on success.</param>
    /// <param name="reason">Why the image was refused, on failure.</param>
    internal static bool TryDecode(
        ReadOnlySpan<byte> bytes,
        int size,
        out WindowIconImage image,
        out string? reason)
    {
        image = default;

        ImageData decoded;
        try
        {
            decoded = PngImage.Decode(bytes);
        }
        catch (Exception exception) when (exception is InvalidDataException
            or ArgumentException
            or IndexOutOfRangeException
            or NotSupportedException)
        {
            // A truncated, mangled or foreign resource lands here. The window simply keeps the
            // platform's default icon.
            reason = exception.Message;
            return false;
        }

        if (size > 0 && (decoded.Width != size || decoded.Height != size))
        {
            reason = string.Create(
                CultureInfo.InvariantCulture,
                $"the resource is {decoded.Width}×{decoded.Height}, not {size}×{size}");
            return false;
        }

        WindowIconImage candidate = new(decoded.Width, decoded.Height, decoded.Pixels);
        if (!candidate.IsWellFormed)
        {
            reason = "the decoded buffer is not Width × Height RGBA";
            return false;
        }

        image = candidate;
        reason = null;
        return true;
    }

    /// <summary>
    /// Decodes the embedded icon and puts it on <paramref name="target"/>, in one call, for the
    /// start-up sequence.
    /// </summary>
    /// <param name="target">The window, or <see langword="null"/> when there is none.</param>
    /// <param name="log">Where the single line describing the outcome goes.</param>
    /// <returns>What was put in force, for the tests.</returns>
    internal static WindowIconState Apply(IWindowIconTarget? target, Action<string>? log)
    {
        IReadOnlyList<WindowIconImage> images = Load(out IReadOnlyList<string> problems);
        WindowIconState state = WindowIcon.Apply(target, images);

        // Once: the sizes that went in, plus the reason when something did not. A broken icon is
        // a line in the log and nothing else.
        if (log is not null)
        {
            string detail = problems.Count == 0 ? string.Empty : $" [{string.Join("; ", problems)}]";
            log(state.Describe() + detail);
        }

        return state;
    }
}
