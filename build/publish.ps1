<#
.SYNOPSIS
    Produces the self-contained Windows x64 release of Zax.App (phase P7a of PLAN.md).

.DESCRIPTION
    Publishes src/Zax.App as a single folder of files that needs no .NET installed on the
    target machine, then adds the licence, the asset and third-party notices, the French user
    guide and a README.txt, and finally checks the produced build actually starts and plays.

    AMD-024 REQ-PUB-001 and REQ-PUB-002: the release contains no file from the original build.
    The skyboxes are generated by the code (REQ-PUB-003), the interface sounds are synthesised
    (REQ-PUB-005), the interface font is read from the machine at run time without being
    redistributed (REQ-PUB-006), and no game profile is shipped: the library starts with the
    two generic entries « 2D Mode » and « 3D par défaut (sans profil) », and .3dn profiles are
    imported by the user.

    The one asset file the release carries is the television of AMD-025:
    assets/tv/retro_crt_tv.glb, « Retro Crt Tv » by meipal, CC BY 4.0, copied unmodified and
    attributed in ASSETS-LICENSES.md. The script verifies that no other asset file slipped
    into the output, and that this one is there.

.PARAMETER Television
    The glTF model of AMD-025. Default: assets-free/tv/retro-crt-tv/retro_crt_tv.glb next to
    the clean-room tree. The release is still produced without it, with the TV option disabled.

.PARAMETER Output
    Where the release goes. Default: impl/artifacts/zaxnes-win-x64.

.PARAMETER Configuration
    Build configuration. Default: Release.

.PARAMETER Roms
    Folder holding the ROM the smoke runs play. Default: the folder the environment variable
    ZAXNES_ROMS names. No machine path is written in this repository (lot PUB-1): with neither
    the variable nor this parameter, the two ROM smoke runs are skipped with a message and the
    rest of the publish still runs.

.PARAMETER ImportProfile
    Optional .3dn profile the third smoke run imports into a throw-away user folder, to check
    the import path of REQ-PUB-001. Nothing in the release depends on it.

.PARAMETER ImportRom
    The ROM the imported profile is played on. Defaults to the ROM of the second smoke run.
    A profile and a ROM are paired freely (REQ-PROF-064), but a profile made for its own game
    is what exercises the 3D conversion in full.

.PARAMETER PlaySeconds
    Seconds of emulated play the game smoke run must reach. Default 60, as REQ-PUB-001 asks.

.PARAMETER SkipChecks
    Publish only, without starting the produced build.

.EXAMPLE
    powershell -File build/publish.ps1

.EXAMPLE
    $env:ZAXNES_ROMS = '<your ROM folder>'; powershell -File build/publish.ps1

.EXAMPLE
    powershell -File build/publish.ps1 -Roms '<your ROM folder>' `
        -ImportProfile '<your profile>.3dn'

.NOTES
    Runs under Windows PowerShell 5.1 as well as PowerShell 7+.

    This file must stay UTF-8 *with* a BOM: Windows PowerShell 5.1 reads a BOM-less file as
    ANSI, and the README text below holds French accents and an em dash — whose third UTF-8
    byte, 0x94, is a closing smart quote in CP1252 and would end a string mid-line.
#>

[CmdletBinding()]
param(
    [string]$Output,
    [string]$Configuration = 'Release',
    [string]$Roms = $env:ZAXNES_ROMS,
    [string]$ImportProfile,
    [string]$ImportRom,
    [string]$Television,
    [int]$PlaySeconds = 60,
    [switch]$SkipChecks
)

$ErrorActionPreference = 'Stop'

$root = Split-Path -Parent $PSScriptRoot
if (-not $Output) { $Output = Join-Path $root 'artifacts\zaxnes-win-x64' }

$project = Join-Path $root 'src\Zax.App\Zax.App.csproj'
if (-not (Test-Path $project)) { throw "publish: $project was not found." }

Write-Host "publish: project       $project"
Write-Host "publish: configuration $Configuration, win-x64, self-contained"
Write-Host "publish: output        $Output"

# ---------------------------------------------------------------- 1. publish

if (Test-Path $Output) { Remove-Item -Recurse -Force $Output }
New-Item -ItemType Directory -Force -Path $Output | Out-Null

# Single folder, no NativeAOT (PLAN.md P6): a plain self-contained publish keeps the native
# dependencies the host needs next to the executable — glfw3, cimgui, lua54 and OpenAL Soft.
& dotnet publish $project `
    -c $Configuration `
    -r win-x64 `
    --self-contained true `
    -p:PublishSingleFile=false `
    -p:PublishReadyToRun=false `
    -p:PublishTrimmed=false `
    -p:SatelliteResourceLanguages=en `
    -p:GenerateDocumentationFile=false `
    -p:DebugType=none `
    -o $Output `
    --nologo `
    -v minimal
if ($LASTEXITCODE -ne 0) { throw "publish: dotnet publish failed with $LASTEXITCODE." }

$exe = Join-Path $Output 'Zaxnes.exe'
if (-not (Test-Path $exe)) { throw "publish: $exe was not produced." }

# The .xml documentation files are a build artefact, not something a user needs. The app
# assembly is named after the product (Zaxnes.xml), the libraries after the code (Zax.*.xml).
# -Include needs a wildcard in -Path to apply to the children rather than to the folder itself.
Get-ChildItem -Path (Join-Path $Output '*') -Include 'Zax.*.xml', 'Zaxnes.xml' -File |
    Remove-Item -Force

# ---------------------------------------------------------------- 2. licence and documents

Copy-Item (Join-Path $root 'LICENSE') (Join-Path $Output 'LICENSE') -Force
Copy-Item (Join-Path $root 'HOWTO-RUN.md') (Join-Path $Output 'HOWTO-RUN.md') -Force
Copy-Item (Join-Path $root 'ASSETS-LICENSES.md') (Join-Path $Output 'ASSETS-LICENSES.md') -Force
Copy-Item (Join-Path $root 'THIRD-PARTY-NOTICES.md') (Join-Path $Output 'THIRD-PARTY-NOTICES.md') -Force

$version = (Select-String -Path (Join-Path $root 'Directory.Build.props') `
    -Pattern '<InformationalVersion>(.+?)</InformationalVersion>').Matches[0].Groups[1].Value

$readme = @"
Zaxnes $version — émulateur NES avec rendu 3D
==========================================

Build Windows x64 autonome : aucun .NET à installer. Lancez Zaxnes.exe.

    Zaxnes.exe
    Zaxnes.exe --rom "jeu.nes" --profile "3D par défaut (sans profil)"
    Zaxnes.exe --rom "jeu.nes" --profile "2D Mode"
    Zaxnes.exe --help

AUCUN ASSET N'EST NÉCESSAIRE. Les skyboxes et les sons d'interface sont produits par le code ;
la police de l'interface est une police déjà installée sur votre Windows (Segoe UI, sinon
Arial), lue au lancement et jamais redistribuée. Il n'y a pas de musique de menu. Le seul
fichier d'asset livré est le boîtier TV, « Retro Crt Tv » de meipal, sous licence CC BY 4.0
(assets/tv/retro_crt_tv.glb) ; sans lui, l'option « Boîtier TV » est simplement désactivée.
Détail et licences : ASSETS-LICENSES.md.

AUCUNE ROM N'EST FOURNIE. Utilisez une ROM dont vous disposez légalement.

AUCUN PROFIL DE JEU N'EST FOURNI. La bibliothèque démarre avec deux entrées génériques :
« 2D Mode » (l'image de la console, sans conversion) et « 3D par défaut (sans profil) » (la
géométrie 3D par défaut, pour n'importe quelle ROM). Si vous disposez légalement d'un profil
« .3dn », importez-le par Fichier ▸ Importer un profil… : il est copié dans votre dossier de
données et apparaît dans la bibliothèque.

Zaxnes est une réimplémentation indépendante. Il n'est affilié ni à Geod Studio ni à 3dSen, et
ne contient aucun fichier provenant de ce programme.

Prérequis : Windows 10/11 x64, une carte graphique OpenGL 3.3 core. L'audio est facultatif.

Documentation : HOWTO-RUN.md (en français) — menus, raccourcis, options, emplacements de
sauvegarde et ligne de commande complète.

Licence : GNU GPL v3, fichier LICENSE. Le code tiers et les paquets utilisés sont listés
dans THIRD-PARTY-NOTICES.md, les assets dans ASSETS-LICENSES.md.

Vérification non interactive :

    Zaxnes.exe --smoke-test --smoke-frames 120    rend 120 images puis quitte avec 0
    Zaxnes.exe --smoke-emulated 3600 --rom ...    joue 60 s puis quitte avec 0
    Zaxnes.exe --list-profiles                    liste les entrées de la bibliothèque
"@
Set-Content -Path (Join-Path $Output 'README.txt') -Value $readme -Encoding utf8

# ---------------------------------------------------------------- 3. the television (AMD-025)

# The one asset file the release ships: the CC BY 4.0 model, copied unmodified, with its
# attribution in ASSETS-LICENSES.md. Without it the build is still valid; the TV box option is
# simply disabled (AMD-025).
if (-not $Television) {
    $Television = Join-Path (Split-Path -Parent $root) 'assets-free\tv\retro-crt-tv\retro_crt_tv.glb'
}

$televisionName = 'retro_crt_tv.glb'
if (Test-Path $Television) {
    $tvFolder = Join-Path $Output 'assets\tv'
    New-Item -ItemType Directory -Force -Path $tvFolder | Out-Null
    Copy-Item $Television (Join-Path $tvFolder $televisionName) -Force

    $source = Get-Item $Television
    $copy = Get-Item (Join-Path $tvFolder $televisionName)
    if ($source.Length -ne $copy.Length) {
        throw 'publish: AMD-025 — the television model was not copied unmodified.'
    }

    Write-Host "publish: television model copied to assets\tv\$televisionName ($([math]::Round($copy.Length / 1MB, 1)) MB)"
} else {
    Write-Warning "publish: AMD-025 — $Television was not found; the TV box option will be disabled."
}

# ---------------------------------------------------------------- 4. no other asset (REQ-PUB-002)

#. '.ico' is here for lot ICON-1: the application icon travels *inside* Zaxnes.exe — the Win32
#  icon resource compiled from branding/zaxnes.ico, and the PNG sizes embedded as assembly
#  resources for the window icon — so the release gains no file at all, and a stray icon or PNG
#  next to the executable is still a REQ-PUB-002 failure.
$assetExtensions = @(
    '.bytes', '.3dn', '.png', '.jpg', '.jpeg', '.bmp', '.tga', '.dds', '.ico',
    '.obj', '.fbx', '.gltf', '.glb', '.wav', '.ogg', '.mp3', '.ttf', '.otf')
$stowaways = Get-ChildItem -Recurse -File $Output |
    Where-Object { $assetExtensions -contains $_.Extension.ToLowerInvariant() } |
    Where-Object { $_.Name -ne $televisionName }
if ($stowaways) {
    $names = ($stowaways | ForEach-Object { $_.Name }) -join ', '
    throw "publish: REQ-PUB-002 — the release carries asset files: $names"
}
Write-Host 'publish: no asset file but the CC BY television in the output (REQ-PUB-002 OK)'

$size = [math]::Round(((Get-ChildItem -Recurse -File $Output | Measure-Object -Sum Length).Sum / 1MB), 1)
$count = (Get-ChildItem -Recurse -File $Output | Measure-Object).Count
Write-Host "publish: $count files, $size MB in $Output"

if ($SkipChecks) {
    Write-Host 'publish: checks skipped (-SkipChecks).'
    exit 0
}

# ---------------------------------------------------------------- 5. does it start and play?

$userdata = Join-Path ([System.IO.Path]::GetTempPath()) ("zaxnes-publish-" + [System.Guid]::NewGuid().ToString('N'))

function Invoke-Smoke {
    param([string]$Label, [string[]]$Arguments)

    Write-Host "publish: smoke '$Label'"

    # Zax.App is a WinExe: PowerShell does not wait for a GUI-subsystem process invoked with
    # '&', and its exit code would never be read. Start-Process -Wait -PassThru does both, and
    # the two streams have to go to files to be captured at all.
    New-Item -ItemType Directory -Force -Path $userdata | Out-Null
    $stdout = Join-Path $userdata "$($Label -replace '[^a-zA-Z0-9]', '-')-out.txt"
    $stderr = Join-Path $userdata "$($Label -replace '[^a-zA-Z0-9]', '-')-err.txt"

    # Start-Process joins -ArgumentList with spaces and quotes nothing itself, so a ROM path
    # or a profile title holding a space ('3D par défaut (sans profil)') would reach Zax.App
    # split in two.
    $quoted = @($Arguments | ForEach-Object { if ($_ -match '\s') { '"' + $_ + '"' } else { $_ } })

    $process = Start-Process -FilePath $exe -ArgumentList $quoted `
        -Wait -PassThru -NoNewWindow `
        -RedirectStandardOutput $stdout -RedirectStandardError $stderr

    $lines = @()
    foreach ($file in @($stdout, $stderr)) {
        if (Test-Path $file) { $lines += @(Get-Content $file) }
    }
    $lines | ForEach-Object { Write-Host "    $_" }

    if ($process.ExitCode -ne 0) {
        throw "publish: smoke '$Label' exited with $($process.ExitCode)."
    }

    return $lines
}

function Assert-Played {
    param([string[]]$Lines, [string]$Label, [int]$Wanted)

    $found = $Lines | Select-String -Pattern 'emulated (\d+)' | Select-Object -First 1
    $emulated = if ($found) { [int]$found.Matches[0].Groups[1].Value } else { 0 }
    $seconds = [math]::Round($emulated / 60.0, 1)
    if ($emulated -lt $Wanted) {
        throw "publish: '$Label' only emulated $emulated frames ($seconds s), $Wanted wanted."
    }

    Write-Host "publish: $emulated emulated frames, $seconds s played in '$Label'"
}

$playFrames = $PlaySeconds * 60

try {
    # 1. REQ-PUB-001: the window, the GL context and the welcome screen come up with no asset
    #    folder of any kind, and 120 frames are drawn.
    Invoke-Smoke 'welcome screen, no assets' @(
        '--smoke-test', '--smoke-frames', '120',
        '--userdata', (Join-Path $userdata 'a')) | Out-Null

    # 2. REQ-PUB-001: Elevator Action, with no profile, plays 60 s in 3D on the default
    #    geometry. A smoke run is unpaced (no vsync, no target rate) while the emulation still
    #    advances on the wall clock at 60 Hz, so --smoke-emulated is what measures the play.
    $rom = if ($Roms) { Join-Path $Roms 'Elevator Action (USA).nes' } else { $null }
    if (-not $Roms) {
        Write-Warning ('publish: no ROM folder — set the environment variable ZAXNES_ROMS, ' +
            'or pass -Roms <dir>, to run the ROM smoke runs. No ROM is shipped with this ' +
            'repository; use one you legally own.')
    } elseif (Test-Path $rom) {
        $lines = Invoke-Smoke 'Elevator Action in 3D without a profile' @(
            '--rom', $rom, '--profile', '3D par défaut (sans profil)',
            '--skybox', 'gradient', '--tv', '1',
            '--smoke-emulated', "$playFrames",
            '--userdata', (Join-Path $userdata 'b'))
        Assert-Played -Lines $lines -Label 'Elevator Action in 3D without a profile' -Wanted $playFrames
    } else {
        Write-Warning "publish: $rom was not found; the game smoke run was skipped."
    }

    # 3. REQ-PUB-001: an imported .3dn profile still works. The file is copied into the user
    #    folder the way « Fichier > Importer un profil… » does, and the game is launched on the
    #    identifier the profile declares.
    if ($ImportProfile) {
        if (-not (Test-Path $ImportProfile)) {
            throw "publish: -ImportProfile $ImportProfile was not found."
        }

        $importRom = if ($ImportRom) { $ImportRom } else { $rom }
        if (-not $importRom) {
            Write-Warning ('publish: no ROM to play the imported profile on; set ZAXNES_ROMS ' +
                'or pass -ImportRom <file>. The import smoke run was skipped.')
        } elseif (-not (Test-Path $importRom)) {
            Write-Warning "publish: $importRom was not found; the import smoke run was skipped."
        } else {
            $importRoot = Join-Path $userdata 'c'
            $profiles = Join-Path $importRoot 'profiles'
            New-Item -ItemType Directory -Force -Path $profiles | Out-Null
            $copy = Join-Path $profiles ([System.IO.Path]::GetFileName($ImportProfile))
            Copy-Item $ImportProfile $copy -Force
            Write-Host "publish: imported $copy"

            # --profile takes the file: the host reads its Id and finds the library entry the
            # scan of <root>/profiles created, whatever title the profile carries.
            $lines = Invoke-Smoke 'the imported profile plays its game' @(
                '--rom', $importRom, '--profile', $copy,
                '--skybox', 'fantasy', '--tv', '1',
                '--smoke-emulated', "$playFrames",
                '--userdata', $importRoot)
            Assert-Played -Lines $lines -Label 'the imported profile plays its game' -Wanted $playFrames

            if ($lines | Select-String -Pattern 'Falling back to 2D Mode|no game matches') {
                throw 'publish: the imported profile was not used.'
            }
        }
    } else {
        Write-Host 'publish: no -ImportProfile given; the import smoke run was skipped.'
    }
} finally {
    Remove-Item -Recurse -Force $userdata -ErrorAction SilentlyContinue
}

Write-Host "publish: OK — $Output"
exit 0
